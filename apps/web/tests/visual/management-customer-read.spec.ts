import { test, expect } from "@playwright/test";
import { fixture } from "./fixtures";
const base = { id: "tab-test", display_label: "Comanda de teste", state: "OPEN", exposure_cents: 1000, effective_limit_cents: 10000, remaining_capacity_cents: 9000, action_reasons: [], override_expires_at: null, customer_id: null, approval_requested: false };
async function refresh(page: import("@playwright/test").Page) {
  await page.getByRole("button", { name: "Atualizar comandas", exact: true }).click();
  await expect(page.getByRole("button", { name: "Atualizar comandas", exact: true })).toBeEnabled();
}
test("customer selected tab tracks canonical values and does not reselect a returning tab", async ({ page }) => {
  await fixture(page, "normal", true);
  let rows = [base];
  await page.route("**/api/auth/me", r => r.fulfill({ json: { staff: { id: "manager-test" }, venue: { id: "venue-test" }, session: { id: "session-test" }, capabilities: ["tab.limit.override"] } }));
  await page.route("**/api/pos/tabs/?active=true&offset=*", r => r.fulfill({ json: { results: rows, next_offset: null } }));
  await page.route("**/api/pos/tabs/tab-test/house-history/", r => r.fulfill({ json: { results: [] } }));
  await page.goto("/manage/customers");
  const select = page.getByLabel("Inspecionar comanda", { exact: true });
  await select.selectOption(base.id);
  const amount = page.getByLabel("Novo limite total (centavos)", { exact: true });
  await expect(amount).toBeEnabled();
  await amount.fill("15000");
  rows = [{ ...base, effective_limit_cents: 20000, remaining_capacity_cents: 19000 }];
  await refresh(page);
  await expect(page.getByText("Limite efetivo", { exact: true }).locator("..").locator("strong")).toHaveText("R$ 200,00");
  await expect(amount).toHaveValue("15000");
  rows = [];
  await refresh(page);
  await expect(select).toHaveValue("");
  await expect(amount).toHaveCount(0);
  rows = [base];
  await refresh(page);
  await expect(select).toHaveValue("");
  await expect(amount).toHaveCount(0);
});
test("customer refresh preserves ambiguous override payload and actor change clears selection", async ({ page }) => {
  await fixture(page, "normal", true);
  let actor = "manager-test";
  await page.route("**/api/auth/me", r => r.fulfill({ json: { staff: { id: actor }, venue: { id: "venue-test" }, session: { id: "session-test" }, capabilities: ["tab.limit.override"] } }));
  await page.route("**/api/pos/tabs/?active=true&offset=*", r => r.fulfill({ json: { results: [base], next_offset: null } }));
  await page.route("**/api/pos/tabs/tab-test/house-history/", r => r.fulfill({ json: { results: [] } }));
  const commands: unknown[] = [];
  await page.route("**/api/pos/tabs/tab-test/limit-override/", route => { commands.push(route.request().postDataJSON()); return route.abort("failed"); });
  await page.goto("/manage/customers");
  await page.getByLabel("Inspecionar comanda", { exact: true }).selectOption(base.id);
  const amount = page.getByLabel("Novo limite total (centavos)", { exact: true });
  await expect(amount).toBeEnabled();
  await amount.fill("15000");
  await page.getByLabel("Motivo", { exact: true }).fill("Autorização de teste");
  const pin = page.getByLabel("Seu PIN de aprovação", { exact: true });
  await pin.fill("0000");
  await page.getByRole("button", { name: "Aprovar limite temporário", exact: true }).click();
  await expect(amount).toBeDisabled();
  await expect(pin).toBeEnabled();
  await refresh(page);
  await expect(amount).toBeDisabled();
  await pin.fill("0000");
  await page.getByRole("button", { name: "Aprovar limite temporário", exact: true }).click();
  await expect(pin).toBeEnabled();
  expect(commands).toHaveLength(2);
  expect(commands[1]).toEqual(commands[0]);
  actor = "manager-other-test";
  await refresh(page);
  await expect(page.getByLabel("Inspecionar comanda", { exact: true })).toHaveValue("");
  await expect(pin).toHaveCount(0);
  await expect(amount).toHaveCount(0);
  expect(commands).toHaveLength(2);
});
test("customer failed initial read remains stale and sends no command", async ({ page }) => {
  await fixture(page, "normal", true);
  await page.route("**/api/pos/tabs/?active=true&offset=*", route => route.abort("failed"));
  const writes: string[] = [];
  page.on("request", r => { if (r.url().includes("/api/") && !["GET", "HEAD"].includes(r.method())) writes.push(r.url()); });
  await page.goto("/manage/customers");
  await expect(page.getByRole("main").getByRole("alert")).toBeVisible();
  await expect(page.getByText("Dados desatualizados. Atualize a conexão antes de aprovar consumo.")).toBeVisible();
  await expect(page.getByText("Atualizando limites…", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Aprovar limite temporário", exact: true })).toHaveCount(0);
  expect(writes).toEqual([]);
});

import { test, expect } from "@playwright/test";
import { fixture, layoutAndA11y, stable } from "./fixtures";
const variant = { id: "variant-test", name: "Variação com nome extenso para conferir disponibilidade", price_cents: 1250, active: true, is_default: true, sort_order: 0, version: 3, availability: "AVAILABLE" };
const option = { id: "option-test", name: "Opção com nome extenso para conferir disponibilidade", price_delta_cents: 250, active: true, default_selected: false, semantic_kind: "ADD", sort_order: 0, version: 2, availability: "UNAVAILABLE" };
for (const width of [360, 390, 430, 1280]) test(`customization availability ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 932 });
  await fixture(page);
  let reads = 0;
  await page.route("**/api/pos/catalog/products/*/customization/", r => { reads++; return r.fulfill({ json: { variants: [variant], modifier_groups: [{ id: "group-test", name: "Grupo de teste", active: true, selection_mode: "MULTI", min_selections: 0, max_selections: 3, version: 1, sort_order: 0, options: [option] }], reusable_groups: [] } }); });
  await page.goto("/manage/catalog");
  await expect(page.getByLabel("Produto", { exact: true }).locator("option")).not.toHaveCount(1);
  await page.getByLabel("Produto", { exact: true }).selectOption({ index: 1 });
  const unavailable = page.getByRole("button", { name: `Indisponibilizar ${variant.name}`, exact: true });
  await expect(unavailable).toBeVisible();
  const section = page.locator("section.panel").filter({ has: page.getByRole("heading", { name: "Variações e opções disponíveis", exact: true }) });
  await stable(page);
  const phase = process.env.RODADA_S4E_BASELINE === "1" ? "before" : "after";
  await section.screenshot({ path: `../../visual-artifacts/spec034-customization-availability/${phase}-${width}.png` });
  if (phase === "before") return;
  await expect(page.getByRole("region", { name: "Variações e opções disponíveis", exact: true })).toBeVisible();
  await layoutAndA11y(page);
  await page.addStyleTag({ content: '[data-management-availability] { zoom: 2; }' });
  await layoutAndA11y(page);
  await section.screenshot({ path: `../../visual-artifacts/spec034-customization-availability/after-${width}-zoom200.png` });
  const requests: { state: string; expected_version: number }[] = [];
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/availability/", async route => { requests.push(route.request().postDataJSON()); await gate; await route.fulfill({ status: 403, json: { message: "Sem permissão para alterar disponibilidade." } }); });
  await unavailable.click();
  await expect(unavailable).toBeDisabled();
  const reactivate = page.getByRole("button", { name: `Reativar ${option.name}`, exact: true });
  await expect(reactivate).toBeDisabled();
  release();
  await expect(section.getByRole("alert")).toBeVisible();
  await expect(unavailable).toBeEnabled();
  await reactivate.click();
  await expect(reactivate).toBeEnabled();
  expect(requests).toEqual([{ state: "UNAVAILABLE", expected_version: 3 }, { state: "AVAILABLE", expected_version: 2 }]);
  expect(reads).toBeGreaterThanOrEqual(3);
  await expect(unavailable).toBeVisible();
  await expect(reactivate).toBeVisible();
});

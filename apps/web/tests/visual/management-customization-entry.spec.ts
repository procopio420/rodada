import { test, expect } from "@playwright/test";
import { fixture, layoutAndA11y, stable } from "./fixtures";
for (const width of [360, 390, 430, 1280]) test(`customization entry ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 932 });
  await fixture(page);
  await page.route("**/api/pos/catalog/products/*/customization/", route => route.fulfill({ json: { variants: [], modifier_groups: [], reusable_groups: [] } }));
  const writes: string[] = [];
  page.on("request", r => { if (r.url().includes("/api/") && !["GET", "HEAD"].includes(r.method())) writes.push(r.url()); });
  await page.goto("/manage/catalog");
  await expect(page.getByRole("heading", { name: "Variações e adicionais", exact: true })).toBeVisible();
  await expect(page.getByLabel("Produto", { exact: true }).locator("option")).not.toHaveCount(1);
  await stable(page);
  const phase = process.env.RODADA_S4B_BASELINE === "1" ? "before" : "after";
  await page.screenshot({ path: `../../visual-artifacts/spec034-customization-entry/${phase}-${width}.png`, fullPage: true });
  if (phase === "before") return;
  await expect(page.getByRole("link", { name: "Voltar ao Cardápio", exact: true })).toHaveAttribute("href", "/manage#cardapio");
  await expect(page.getByLabel("Produto", { exact: true })).toHaveAccessibleDescription("Escolha o produto para consultar suas variações e grupos de opções.");
  await layoutAndA11y(page);
  await page.addStyleTag({ content: "main { zoom: 2; }" });
  await layoutAndA11y(page);
  await page.screenshot({ path: `../../visual-artifacts/spec034-customization-entry/after-${width}-zoom200.png`, fullPage: true });
  await page.getByLabel("Produto", { exact: true }).selectOption({ index: 1 });
  await expect(page.getByRole("button", { name: "Criar variação", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Criar variação", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Criar variação", exact: true })).toBeVisible();
  await page.getByLabel("Produto", { exact: true }).selectOption("");
  await expect(page.getByRole("heading", { name: "Criar variação", exact: true })).toHaveCount(0);
  expect(writes).toEqual([]);
});

import { test, expect } from "@playwright/test";
import { fixture } from "./fixtures";
test.beforeEach(async ({ page }) => {
  await fixture(page);
  await page.route("**/api/auth/me", r => r.fulfill({ json: { capabilities: ["catalog.icon.manage", "catalog.product.create"] } }));
  await page.route("**/api/pos/catalog/suggestions/**", r => r.fulfill({ json: { results: [] } }));
});
test("quick catalog restarts search on return and reopening but not when already open", async ({ page }) => {
  const writes: string[] = [];
  page.on("request", r => { if (r.url().includes("/api/") && !["GET", "HEAD"].includes(r.method())) writes.push(r.url()); });
  await page.goto("/manage/products");
  const trigger = page.getByRole("button", { name: "Adicionar produto", exact: true });
  await trigger.click();
  const name = page.getByRole("combobox", { name: "Nome do produto", exact: true });
  await name.fill("Produto de teste");
  const create = page.getByRole("option", { name: "Criar “Produto de teste”", exact: true });
  await expect(create).toBeVisible();
  await trigger.click();
  await expect(create).toBeVisible();
  await create.click();
  await expect(page.getByLabel("Preço (R$)")).toBeVisible();
  await page.getByRole("button", { name: "Voltar", exact: true }).click();
  await expect(create).toBeVisible();
  await expect(name).toHaveValue("Produto de teste");
  await page.getByRole("button", { name: "Fechar", exact: true }).click();
  await expect(trigger).toBeFocused();
  await trigger.click();
  await expect(name).toHaveValue("");
  await expect(create).toHaveCount(0);
  await name.fill("Outro produto de teste");
  await expect(page.getByRole("option", { name: "Criar “Outro produto de teste”", exact: true })).toBeVisible();
  expect(writes).toEqual([]);
});
test("quick catalog hides stale creation while current search is pending", async ({ page }) => {
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  let started = false;
  await page.route("**/api/pos/catalog/suggestions/?q=Segundo", async route => { started = true; await gate; await route.fulfill({ json: { results: [] } }); });
  await page.goto("/manage/products");
  await page.getByRole("button", { name: "Adicionar produto", exact: true }).click();
  const name = page.getByRole("combobox", { name: "Nome do produto", exact: true });
  await name.fill("Primeiro");
  await expect(page.getByRole("option", { name: "Criar “Primeiro”", exact: true })).toBeVisible();
  await name.fill("Segundo");
  await expect.poll(() => started).toBe(true);
  await expect(page.getByRole("listbox", { name: "Produtos existentes", exact: true }).getByRole("option")).toHaveCount(0);
  await name.press("Enter");
  await expect(page.getByLabel("Preço (R$)")).toHaveCount(0);
  release();
  await expect(page.getByRole("option", { name: "Criar “Segundo”", exact: true })).toBeVisible();
});

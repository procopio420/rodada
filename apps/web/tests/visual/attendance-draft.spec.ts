import { expect, test } from "@playwright/test";
import { fixture, layoutAndA11y } from "./fixtures";
for (const width of [360, 390, 430]) test(`Attendance draft quantity and collapse at ${width}`, async ({ page }) => {
 await fixture(page, "normal", true);
 await page.setViewportSize({ width, height: 900 });
 await page.goto("/attendance");
 await page.getByRole("button", { name: "Contas", exact: true }).click();
 const tab = page.getByRole("button", { name: /Comanda de teste ·/ });
 await tab.click();
 const draft = page.getByRole("region", { name: "Pedido atual" });
 await page.getByRole("button", { name: /^Fritas/ }).click();
 await expect(draft.getByText("1× Fritas", { exact: true })).toBeVisible();
 await draft.getByRole("button", { name: "Aumentar quantidade de Fritas", exact: true }).click();
 await expect(draft.getByText("2× Fritas", { exact: true })).toBeVisible();
 await page.getByRole("button", { name: /^Fritas/ }).click();
 await expect(draft.getByText("3× Fritas", { exact: true })).toBeVisible();
 await expect(draft.locator("article")).toHaveCount(1);
 await expect(draft.getByText("R$ 216,00", { exact: true })).toBeVisible();
 const placement = await page.locator(".attendanceOrders").evaluate(el => {
  const draft = el.querySelector('[aria-label="Pedido atual"]');
  const catalog = [...el.querySelectorAll("h2")].find(h => h.textContent === "Catálogo");
  return !!draft && !!catalog && !!(draft.compareDocumentPosition(catalog) & Node.DOCUMENT_POSITION_FOLLOWING);
 });
 expect(placement).toBe(true);
 await layoutAndA11y(page);
 await page.screenshot({ path: `../../visual-artifacts/pilot-cohesion/attendance-draft-${width}.png`, fullPage: true });
 await tab.click();
 await expect(draft).toBeVisible();
 await expect(tab).toHaveAttribute("aria-expanded", "true");
 await tab.click();
 await expect(draft.getByText("3× Fritas", { exact: true })).toBeVisible();
 const title = page.getByRole("button", { name: /Comanda selecionada Comanda de teste/ });
 await title.click();
 await expect(draft).not.toBeVisible();
 await title.click();
 await draft.getByRole("button", { name: "Diminuir quantidade de Fritas", exact: true }).click();
 await draft.getByRole("button", { name: "Diminuir quantidade de Fritas", exact: true }).click();
 await draft.getByRole("button", { name: "Diminuir quantidade de Fritas", exact: true }).click();
 await expect(draft.locator("article")).toHaveCount(0);
 await expect(draft.getByRole("button", { name: /Confirmar pedido/ })).toBeDisabled();
 await layoutAndA11y(page);
});

import { expect, test } from "@playwright/test";
import { fixture, layoutAndA11y } from "./fixtures";
import { openAttendanceTab } from "./attendance-actions";
import { addCatalogItem, expectCatalogQuantity } from "./category-actions";
for (const width of [360, 390, 430]) test(`Attendance draft quantity and context at ${width}`, async ({ page }) => {
  await fixture(page, "normal", true);
  await page.setViewportSize({ width, height: 900 });
  await page.goto("/attendance");
  await openAttendanceTab(page);
  const workspace = page.locator(".attendanceOrderDialog");
  await addCatalogItem(page, "Fritas");
  await expectCatalogQuantity(page, "Fritas", 1);
  await workspace.getByRole("button", { name: /^Pedido atual/ }).click();
  const draft = workspace.getByRole("region", { name: "Pedido atual" });
  await expect(draft.getByText("1× Fritas", { exact: true })).toBeVisible();
  await draft.getByRole("button", { name: "Aumentar quantidade de Fritas", exact: true }).click();
  await expect(draft.getByText("2× Fritas", { exact: true })).toBeVisible();
  await workspace.getByRole("button", { name: "Cardápio", exact: true }).click();
  await addCatalogItem(page, "Fritas");
  await expectCatalogQuantity(page, "Fritas", 3);
  await workspace.getByRole("button", { name: /^Pedido atual/ }).click();
  await expect(draft.getByText("3× Fritas", { exact: true })).toBeVisible();
  await expect(draft.locator("article")).toHaveCount(1);
  await expect(draft.getByText("R$ 216,00", { exact: true })).toBeVisible();
  await layoutAndA11y(page);
  await workspace.locator(":scope > button").last().click();
  await expect(workspace).not.toBeVisible();
  await openAttendanceTab(page);
  await workspace.getByRole("button", { name: /^Pedido atual/ }).click();
  await expect(draft.getByText("3× Fritas", { exact: true })).toBeVisible();
  for (let n = 0; n < 3; n++) await draft.getByRole("button", { name: "Diminuir quantidade de Fritas", exact: true }).click();
  await expect(draft.locator("article")).toHaveCount(0);
  await expect(draft.getByRole("button", { name: /Confirmar pedido/ })).toBeDisabled();
  await layoutAndA11y(page);
});

import { expect, test } from "@playwright/test";
import { fixture, layoutAndA11y } from "./fixtures";
import { openAttendanceTab, attendanceDraft, closeAttendanceTab } from "./attendance-actions";
import { addCatalogItem, expectCatalogQuantity } from "./category-actions";
for (const width of [360, 390, 430]) test(`Attendance draft quantity and context at ${width}`, async ({ page }) => {
  await fixture(page, "normal", true);
  await page.setViewportSize({ width, height: 900 });
  await page.goto("/attendance");
  await openAttendanceTab(page);
  const workspace = page.getByRole("region", { name: "Comanda selecionada", exact: true });
  await addCatalogItem(page, "Fritas");
  await expectCatalogQuantity(page, "Fritas", 1);
  const draft = await attendanceDraft(page);
  await expect(draft.getByText("1× Fritas", { exact: true })).toBeVisible();
  await draft.getByRole("button", { name: "Aumentar Fritas", exact: true }).click();
  await expect(draft.getByText("2× Fritas", { exact: true })).toBeVisible();
  await workspace.getByRole("button", { name: "← Continuar escolhendo itens", exact: true }).click();
  await addCatalogItem(page, "Fritas");
  await expectCatalogQuantity(page, "Fritas", 3);
  await workspace.getByRole("button", { name: "Ver resumo", exact: true }).click();
  await expect(draft.getByText("3× Fritas", { exact: true })).toBeVisible();
  await expect(draft.locator(".ux2ReviewRow")).toHaveCount(1);
  await expect(draft.locator(".ux2AmountLine").getByText("R$ 216,00", { exact: true })).toBeVisible();
  await layoutAndA11y(page);
  await closeAttendanceTab(page);
  await expect(workspace).not.toBeVisible();
  await openAttendanceTab(page);
  await attendanceDraft(page);
  await expect(draft.getByText("3× Fritas", { exact: true })).toBeVisible();
  for (let n = 0; n < 3; n++) await draft.getByRole("button", { name: "Reduzir Fritas", exact: true }).click();
  await expect(draft.locator(".ux2ReviewRow")).toHaveCount(0);
  await expect(draft.getByRole("button", { name: /Enviar|Adicione itens/ })).toBeDisabled();
  await layoutAndA11y(page);
});

import { expect, test } from "./fixtures";
import crypto from "node:crypto";
import { mkdir } from "node:fs/promises";

for (const width of [360, 390, 430, 1280]) test(`printer route CAS and changed-driver attestation at ${width}px`, async ({ page, request }) => {
  test.setTimeout(60000);
  await page.setViewportSize({ width, height: 900 });
  await page.goto("/staff");
  await page.getByLabel("Estabelecimento").fill("web-e2e");
  await page.getByLabel("Operador", { exact: true }).fill("test-manager");
  await page.getByLabel("PIN", { exact: true }).fill("2468");
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page.getByRole("link", { name: /Continuar trabalhando/ })).toBeVisible();
  await page.goto("/manage/printing");
  const fleet = page.getByRole("region", { name: "Computadores de impressão" });
  const enable = fleet.getByRole("button", { name: "Habilitar computadores de impressão" });
  await expect(enable.or(fleet.getByLabel("Código de pareamento"))).toBeVisible();
  if (await enable.isVisible()) await enable.click();
  const api = `http://127.0.0.1:${process.env.RODADA_E2E_API_PORT ?? "8100"}/printing/agents/v1/`;
  const proof = "rpp_" + crypto.randomBytes(32).toString("base64url");
  const started = await (await request.post(api + "pairing/start/", { data: { installation_id: crypto.randomUUID(), label: `PC Rotas ${width}`, proof } })).json();
  await fleet.getByLabel("Código de pareamento").fill(started.code);
  await fleet.getByRole("button", { name: "Adicionar computador", exact: true }).click();
  await fleet.getByRole("button", { name: "Autorizar este computador", exact: true }).click();
  await expect(fleet.getByRole("status")).toContainText("Computador autorizado");
  const paired = await (await request.post(api + "pairing/status/", { data: { request_id: started.request_id, proof } })).json();
  const headers = { Authorization: "Bearer " + paired.credential };
  expect((await request.post(api + "me/activate/", { headers, data: {} })).status()).toBe(200);
  expect((await request.post(api + "me/heartbeat/", { headers, data: { protocol_version: 1, version: "0.3.0" } })).status()).toBe(200);
  const printer = { local_id: `synthetic-${width}`, label: `Fila sintética ${width}`, queue_name: `Synthetic Queue ${width}`, driver_name: "Synthetic Driver A", transport: "WINDOWS_DRIVER", health: "UNKNOWN" };
  expect((await request.post(api + "me/discovery/", { headers, data: { protocol_version: 1, printers: [printer] } })).status()).toBe(200);
  await page.getByLabel("Nome", { exact: true }).fill(`Destino sintético ${width}`);
  await page.getByRole("combobox", { name: "Saída", exact: true }).selectOption("AGENT");
  await page.getByRole("button", { name: "Salvar destino", exact: true }).click();
  const panel = page.getByRole("region", { name: "Rotas dos computadores" });
  await panel.getByLabel("Destino lógico").focus();
  await page.keyboard.press("Tab");
  await expect(panel.getByLabel("Fila descoberta")).toBeFocused();
  await panel.getByLabel("Destino lógico").selectOption({ label: `Destino sintético ${width}` });
  await expect(panel.getByLabel("Fila descoberta").getByRole("option", { name: `Fila sintética ${width} · estado não confirmado`, exact: true })).toHaveCount(1, { timeout: 15000 });
  await panel.getByLabel("Fila descoberta").selectOption({ label: `Fila sintética ${width} · estado não confirmado` });
  await panel.getByLabel("Usar ESC/POS RAW em vez do driver Windows").check();
  const attestation = panel.getByLabel(/Confirmei em teste físico/);
  const save = panel.getByRole("button", { name: "Salvar rota", exact: true });
  await expect(save).toBeDisabled();
  // Synthetic authorization fixture only: no physical compatibility certification.
  await attestation.check();
  await panel.getByLabel("Habilitar esta rota").check();
  await save.click();
  await expect(panel.getByRole("status")).toContainText("Rota salva");
  const inventory = await page.evaluate(async () => (await (await fetch("/api/pos/printing/agents/v1/routes/")).json()));
  const observed = inventory.printers.find((row: { local_id: string }) => row.local_id === `synthetic-${width}`);
  const route = inventory.routes.find((row: { printer_id: string }) => row.printer_id === observed.id);
  expect(route).toMatchObject({ transport: "WINDOWS_RAW", enabled: true, raw_escpos_verified: true, version: 1 });
  expect((await request.post(api + "me/discovery/", { headers, data: { protocol_version: 1, printers: [{ ...printer, driver_name: "Synthetic Driver B" }] } })).status()).toBe(200);
  await expect(panel.getByRole("alert")).toContainText("A fila ou o driver mudou", { timeout: 15000 });
  await expect(save).toBeDisabled();
  await expect(attestation).not.toBeChecked();
  await panel.getByRole("button", { name: "Revisar dados da impressora" }).click();
  await expect(attestation).not.toBeChecked();
  await expect(panel.getByLabel("Habilitar esta rota")).not.toBeChecked();
  await expect(save).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await mkdir("visual-artifacts/print-agent-routes", { recursive: true });
  await panel.screenshot({ path: `visual-artifacts/print-agent-routes/routes-${width}.png` });
});

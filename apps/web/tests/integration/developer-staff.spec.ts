import { expect, test } from "./fixtures";
test("DEV provisions an operator, edits role and revokes access with canonical readback", async ({ page, browser }) => {
  await page.goto("/dev/staff");
  await page.getByLabel("Estabelecimento").fill("web-e2e");
  await page.getByLabel("Operador",{exact:true}).fill("test-owner");
  await page.getByLabel("PIN",{exact:true}).fill("2468");
  await page.getByRole("button",{name:"Entrar",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Administrar equipe"})).toBeVisible();
  await expect(page.getByRole("button",{name:"Gerenciar test-owner"})).toBeVisible();
  await page.getByLabel("Nome do operador").fill("Developer E2E operator");
  await page.getByLabel("Login do novo operador").fill("developer.e2e.operator");
  await page.getByLabel("PIN do novo operador").fill("7319");
  await page.getByLabel("Seu PIN para confirmar").fill("2468");
  await page.getByRole("button",{name:"Criar operador",exact:true}).click();
  await expect(page.getByRole("button",{name:"Gerenciar Developer E2E operator"})).toBeVisible();
  const context=await browser.newContext();const operator=await context.newPage();
  await operator.goto("/staff");await operator.getByLabel("Estabelecimento").fill("web-e2e");await operator.getByLabel("Operador",{exact:true}).fill("developer.e2e.operator");await operator.getByLabel("PIN",{exact:true}).fill("7319");await operator.getByRole("button",{name:"Entrar",exact:true}).click();
  await expect(operator.getByText("Sessão operacional ativa")).toBeVisible();
  await page.getByRole("button",{name:"Gerenciar Developer E2E operator"}).click();
  await page.getByLabel("Função",{exact:true}).selectOption("CASHIER");
  await page.getByLabel("Seu PIN para confirmar").fill("2468");await page.getByRole("button",{name:"Salvar acesso"}).click();
  await expect(page.getByText("developer.e2e.operator · Caixa · Ativo")).toBeVisible();
  await page.getByRole("button",{name:"Gerenciar Developer E2E operator"}).click();
  await page.getByRole("button",{name:"Remover acesso",exact:true}).click();
  await page.getByLabel("Seu PIN para confirmar").fill("2468");await page.getByRole("button",{name:"Confirmar remoção do acesso"}).click();
  await expect(page.getByRole("button",{name:"Gerenciar Developer E2E operator"})).toHaveCount(0);
  await page.getByRole("button", { name: "Mostrar acessos removidos" }).click();
  await expect(page.getByText("developer.e2e.operator · Caixa · Removido")).toBeVisible();
  const result=await operator.evaluate(async()=> (await fetch("/api/auth/me")).status);
  expect([401,403]).toContain(result);
  await context.close();
});
